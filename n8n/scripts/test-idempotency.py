"""Exercise the inspection RPC on a disposable PostgreSQL database, including races."""
import concurrent.futures
import json
import os
from pathlib import Path
import re
import subprocess
import time


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    folder = root / "n8n/.runtime/idempotency-sql"
    folder.mkdir(parents=True, exist_ok=True)
    name = f"cn360-idempotency-{os.getpid()}"
    case_results: list[dict[str, object]] = []
    report: dict[str, object] = {"database": "postgres:17-alpine", "cases": case_results}

    def command(args: list[str], text: str | None = None, check: bool = True) -> subprocess.CompletedProcess[str]:
        return subprocess.run(args, input=text, capture_output=True, text=True, check=check)

    def sql(query: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        return command(["docker", "exec", "-i", name, "psql", "-U", "postgres", "-qAt", "-v", "ON_ERROR_STOP=1"], query, check)

    def request(session: str | None, item: str | None) -> str:
        body = json.dumps({"controller_session": session, "item_id": item, "verdict": "reject", "model_instruction": "quoted ' operator text"}).replace("'", "''")
        return f"SELECT id,was_inserted FROM public.cn360_record_inspection('{body}'::jsonb);"

    command(["docker", "run", "--rm", "-d", "--name", name, "--network", "none", "--env", "POSTGRES_HOST_AUTH_METHOD=trust", "postgres:17-alpine"])
    try:
        for _ in range(90):
            if command(["docker", "exec", name, "pg_isready", "-U", "postgres"], check=False).returncode == 0:
                break
            time.sleep(0.25)
        else:
            raise RuntimeError("Disposable PostgreSQL did not become ready")
        schema = """
CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
CREATE TABLE public.inspection_results (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz DEFAULT now() NOT NULL,
 inspection_at timestamptz, inspection_target text, model_instruction text,
 camera_session text, frame_sequence bigint, frame_width integer, frame_height integer,
 box_count integer, defect_coverage double precision, coverage_threshold double precision,
 verdict text, prompt_verified boolean, frame_url text, controller_session text, item_id text);
GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT,INSERT ON public.inspection_results TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO service_role;
"""
        sql(schema + (root / "n8n/sql/002-idempotent-inspections.sql").read_text(encoding="utf-8"))
        with concurrent.futures.ThreadPoolExecutor(max_workers=12) as pool:
            first = pool.submit(sql, "BEGIN; SET ROLE service_role;" + request("race", "18446744073709551615") + "SELECT pg_sleep(1); COMMIT;")
            time.sleep(0.1)
            rest = [pool.submit(sql, "SET ROLE service_role;" + request("race", "18446744073709551615")) for _ in range(19)]
            outputs = [first.result().stdout] + [future.result().stdout for future in rest]
        rows = [match for output in outputs for match in re.findall(r"^(\d+)\|([tf])$", output, flags=re.MULTILINE)]
        assert len(rows) == 20 and len({r[0] for r in rows}) == 1
        assert sum(r[1] == "t" for r in rows) == 1
        assert sql("SELECT count(*) FROM inspection_results WHERE controller_session='race';").stdout.strip() == "1"
        case_results.append({"id": "20-concurrent-callers", "passed": True, "rows": rows})
        sql("SET ROLE service_role;" + request("race", "another-item"))
        assert sql("SELECT count(*) FROM inspection_results WHERE controller_session='race';").stdout.strip() == "2"
        case_results.append({"id": "different-items-stay-distinct", "passed": True})
        sql("BEGIN;" + request("rollback", "1") + "ROLLBACK;")
        assert "|t" in sql(request("rollback", "1")).stdout
        case_results.append({"id": "rollback-does-not-poison-claim", "passed": True})
        sql("INSERT INTO inspection_results(controller_session,item_id) VALUES ('legacy','1'),('legacy','1');")
        assert "|f" in sql(request("legacy", "1")).stdout
        assert sql("SELECT count(*) FROM inspection_results WHERE controller_session='legacy';").stdout.strip() == "2"
        case_results.append({"id": "legacy-duplicates-preserved-without-more-inserts", "passed": True})
        assert sql(request("partial", None), check=False).returncode != 0
        assert sql("SET ROLE anon;" + request("anon", "1"), check=False).returncode != 0
        assert sql("BEGIN ISOLATION LEVEL REPEATABLE READ;" + request("isolation", "1"), check=False).returncode != 0
        case_results.append({"id": "invalid-identity-role-and-isolation-refused", "passed": True})
        a = sql(request(None, None)).stdout.strip()
        b = sql(request(None, None)).stdout.strip()
        assert a != b and "|t" in a and "|t" in b
        case_results.append({"id": "observational-records-stay-distinct", "passed": True})
    finally:
        command(["docker", "stop", "--timeout", "2", name], check=False)
        (folder / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
